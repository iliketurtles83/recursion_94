#ifndef MATERIAL_ATLAS_H
#define MATERIAL_ATLAS_H

#include <stdbool.h>
#include <stdint.h>

// Runtime-generated micro-material atlases (RGBA8). Each texel carries four
// independent surface channels consumed by the environment shaders:
//   detail: height / roughness / oxidation / wear
//   facade: stamped relief / roughness / oxidation / edge wear
// Both are pure functions of integer hashes; generation is deterministic and
// happens once at startup into static storage (no heap allocation).
#define DETAIL_ATLAS_SIDE 256
#define FACADE_ATLAS_SIDE 192
#define DETAIL_ATLAS_BYTES (DETAIL_ATLAS_SIDE * DETAIL_ATLAS_SIDE * 4)
#define FACADE_ATLAS_BYTES (FACADE_ATLAS_SIDE * FACADE_ATLAS_SIDE * 4)

// Golden FNV-1a hashes of the generated bytes. They match the atlases that
// were previously baked offline and embedded, so the rendered look is unchanged.
#define DETAIL_ATLAS_FNV1A UINT32_C(0x456b2ed1)
#define FACADE_ATLAS_FNV1A UINT32_C(0x13bcae23)

const unsigned char *GetDetailAtlasBytes(void);
const unsigned char *GetFacadeAtlasBytes(void);
uint32_t MaterialAtlasHash(const unsigned char *bytes, int count);
bool ValidateMaterialAtlases(void);

#endif
