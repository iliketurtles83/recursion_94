// Four reproducible side-environment material tiles. Channels: stamped relief,
// roughness, oxidation/deposits, and exposed metal / edge wear. Every channel is
// consumed by the tower shader; no external asset is needed at runtime.
// Build: cc -std=c11 -O2 tools/bake_facade.c -lm -o bake-facade
// Run: bake-facade src/facade_atlas.h
#include <math.h>
#include <stdint.h>
#include <stdio.h>

#define SIDE 192
#define TILE 96

static uint32_t hash(uint32_t x) {
    x ^= x >> 16; x *= UINT32_C(0x7feb352d);
    x ^= x >> 15; x *= UINT32_C(0x846ca68b);
    return x ^ (x >> 16);
}

static float random01(int x, int y, uint32_t salt) {
    return (float)(hash((uint32_t)x * UINT32_C(1597334677) ^
                        (uint32_t)y * UINT32_C(3812015801) ^ salt) & 65535u) / 65535.0f;
}

static float noise(float x, float y, int period, uint32_t salt) {
    int ix = (int)floorf(x), iy = (int)floorf(y);
    float fx = x - (float)ix, fy = y - (float)iy;
    fx = fx * fx * (3.0f - 2.0f * fx);
    fy = fy * fy * (3.0f - 2.0f * fy);
    float a = random01(ix & (period - 1), iy & (period - 1), salt);
    float b = random01((ix + 1) & (period - 1), iy & (period - 1), salt);
    float c = random01(ix & (period - 1), (iy + 1) & (period - 1), salt);
    float d = random01((ix + 1) & (period - 1), (iy + 1) & (period - 1), salt);
    return (a + (b - a) * fx) * (1.0f - fy) + (c + (d - c) * fx) * fy;
}

static float clamp01(float x) { return x < 0.0f ? 0.0f : x > 1.0f ? 1.0f : x; }
static unsigned char toByte(float x) { return (unsigned char)(clamp01(x) * 255.0f + 0.5f); }

int main(int argc, char **argv) {
    if (argc != 2) return 2;
    FILE *out = fopen(argv[1], "wb");
    if (!out) return 3;
    fputs("// Generated by tools/bake_facade.c: relief / roughness / oxidation / edge wear.\n"
          "#ifndef FACADE_ATLAS_H\n#define FACADE_ATLAS_H\n"
          "#define FACADE_ATLAS_SIDE 192\n"
          "static const unsigned char facade_atlas_bytes[147456] = {\n", out);
    uint32_t checksum = UINT32_C(2166136261);
    for (int y = 0; y < SIDE; y++) for (int x = 0; x < SIDE; x++) {
        int tile = x / TILE + 2 * (y / TILE);
        int u = x % TILE, v = y % TILE;
        int pu = u * 128 / TILE, pv = v * 128 / TILE;
        int cu = u < TILE / 2 ? u : TILE - 1 - u;
        int cv = v < TILE / 2 ? v : TILE - 1 - v;
        float coarse = noise((float)u / 22.0f, (float)v / 22.0f, 8,
                             1049u + (uint32_t)tile * 617u);
        float oxide = noise((float)u / 7.0f, (float)v / 7.0f, 32,
                            3119u + (uint32_t)tile * 883u);
        float grain = random01(u, v, 997u + (uint32_t)tile * 1033u);
        float grain2 = random01(u, v, 2503u + (uint32_t)tile * 227u);
        float grain3 = random01(u, v, 7103u + (uint32_t)tile * 437u);
        float grain4 = random01(u, v, 12097u + (uint32_t)tile * 149u);
        float rolled = noise((float)u / 30.0f, (float)v / 2.0f, 128,
                             607u + (uint32_t)tile * 61u);
        float relief = 0.51f + (coarse - 0.5f) * 0.11f;
        float roughness = 0.47f + oxide * 0.13f;
        float stain = 0.12f + oxide * 0.27f + coarse * 0.09f;
        float wear = 0.10f + grain4 * 0.07f;
        float seam = (cu < 3 || cv < 3) ? 1.0f : 0.0f;
        float fastener = 0.0f;
        float slot = 0.0f;
        float rib = 0.0f;

        if (tile == 0) {
            // Bolted, offset armor plates with thin raised lip, recessed seam
            // and transverse machining marks.
            int row = pv / 32;
            int offset = (row & 1) ? 16 : 0;
            int px = (pu + offset) & 63;
            int py = pv & 31;
            int ex = px < 32 ? px : 63 - px;
            int ey = py < 16 ? py : 31 - py;
            seam = (ex < 2 || ey < 2) ? 1.0f : 0.0f;
            rib = (ex >= 2 && ex < 6) || (ey >= 2 && ey < 5) ? 1.0f : 0.0f;
            int dx = ex - 9, dy = ey - 8;
            fastener = dx * dx + dy * dy < 16 ? 1.0f : 0.0f;
            slot = (px > 25 && px < 39 && py > 12 && py < 16) ? 1.0f : 0.0f;
        } else if (tile == 1) {
            // Louver cassettes: dark throat, individually separated vanes,
            // narrow fixing screws and an oxidized surrounding frame.
            int px = pu & 63, py = pv & 63;
            int ex = px < 32 ? px : 63 - px;
            int ey = py < 32 ? py : 63 - py;
            seam = (ex < 3 || ey < 3) ? 1.0f : 0.0f;
            int inside = px > 8 && px < 55 && py > 9 && py < 55;
            slot = inside && ((py + 1) % 8) < 5 ? 1.0f : 0.0f;
            rib = inside && ((py + 1) % 8) >= 5 ? 1.0f : 0.0f;
            int dx = ex - 5, dy = ey - 5;
            fastener = dx * dx + dy * dy < 9 ? 1.0f : 0.0f;
        } else if (tile == 2) {
            // Diamond grip and utility hatches. Larger quiet regions let the
            // real instanced geometry cast legible silhouette and contact shade.
            int px = pu & 63, py = pv & 63;
            int d1 = (px + py) & 15, d2 = (px - py + 128) & 15;
            rib = (d1 < 2 || d2 < 2) ? 0.65f : 0.0f;
            int hatch = (px > 13 && px < 51 && py > 13 && py < 51);
            seam = (px == 13 || px == 50 || py == 13 || py == 50) ? 1.0f : 0.0f;
            slot = hatch && ((px - 17) % 7 < 3) && py > 21 && py < 43 ? 0.65f : 0.0f;
            fastener = ((px - 9) * (px - 9) + (py - 9) * (py - 9) < 10) ? 1.0f : 0.0f;
        } else {
            // Perforated machine casing, concentric fan ring and guide rails.
            int px = pu & 63, py = pv & 63;
            int dx = px - 32, dy = py - 32;
            int r2 = dx * dx + dy * dy;
            int hx = (px + 4) % 12 - 6, hy = (py + 4) % 12 - 6;
            slot = (hx * hx + hy * hy < 8) ? 1.0f : 0.0f;
            rib = (r2 > 600 && r2 < 800) || px < 5 || py < 5 ? 1.0f : 0.0f;
            seam = (px < 2 || py < 2) ? 1.0f : 0.0f;
            fastener = (px - 7) * (px - 7) + (py - 7) * (py - 7) < 9 ? 1.0f : 0.0f;
        }

        // Rare local scratches, chipped paint and uneven rolled grain remain
        // material information—not random padding. Mipmaps filter them out at
        // distance while the broad stamps/slots survive at gameplay scale.
        uint32_t scratchHash = hash((uint32_t)(u / 26) * 977u ^
                                    (uint32_t)(v / 9) * 577u ^ (uint32_t)tile * 301u);
        float scratch = (v % 9 == (int)(scratchHash % 9u) &&
                         u % 26 < (int)((scratchHash >> 9) % 22u) &&
                         (scratchHash & 3u) == 0u) ? 1.0f : 0.0f;
        float pit = oxide > 0.64f && grain3 > 0.77f ? 1.0f : 0.0f;
        relief += rib * 0.11f + fastener * 0.19f - seam * 0.22f - slot * 0.24f;
        relief += (grain - 0.5f) * 0.044f + (rolled - 0.5f) * 0.050f - pit * 0.075f;
        roughness += seam * 0.12f + slot * 0.16f + oxide * 0.14f;
        roughness += (grain2 - 0.5f) * 0.21f - fastener * 0.23f;
        stain += seam * 0.15f + (slot > 0.0f ? 0.09f : 0.0f) + pit * 0.27f;
        stain += (grain3 - 0.5f) * 0.13f;
        wear += rib * 0.13f + fastener * 0.50f + scratch * 0.62f + pit * 0.09f;
        wear += (grain4 - 0.5f) * 0.105f;
        unsigned char channels[4] = {
            toByte(relief), toByte(roughness), toByte(stain), toByte(wear)
        };
        for (int c = 0; c < 4; c++) {
            checksum = (checksum ^ channels[c]) * UINT32_C(16777619);
            fprintf(out, "%u,", channels[c]);
        }
        if ((x & 7) == 7) fputc('\n', out);
    }
    fputs("};\n#endif\n", out);
    if (fclose(out) != 0) return 4;
    printf("FACADE BAKE: %dx%d RGBA, %d used bytes, FNV1a=%08x\n",
           SIDE, SIDE, SIDE * SIDE * 4, checksum);
    return 0;
}
