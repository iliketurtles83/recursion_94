// Reproducible baked micro-material, not an imported asset or executable padding.
// Build: cc -std=c11 -O2 tools/bake_detail.c -lm -o /tmp/bake-detail
// Run: /tmp/bake-detail src/detail_atlas.h
#include <stdint.h>
#include <stdio.h>
#include <math.h>
#include <stdlib.h>
#define SIDE 256
static uint32_t hash(uint32_t x) {
    x^=x>>16; x*=UINT32_C(0x7feb352d); x^=x>>15;
    x*=UINT32_C(0x846ca68b); return x^(x>>16);
}
static float cell(int x,int y,int period,uint32_t seed) {
    return (float)(hash((uint32_t)(x&(period-1))*1597334677u^
                       (uint32_t)(y&(period-1))*3812015801u^seed)&65535u)/65535.0f;
}
static float noise(float x,float y,int period,uint32_t seed) {
    int ix=(int)floorf(x),iy=(int)floorf(y);
    float fx=x-ix,fy=y-iy; fx=fx*fx*(3-2*fx); fy=fy*fy*(3-2*fy);
    float a=cell(ix,iy,period,seed),b=cell(ix+1,iy,period,seed);
    float c=cell(ix,iy+1,period,seed),d=cell(ix+1,iy+1,period,seed);
    return (a+(b-a)*fx)*(1-fy)+(c+(d-c)*fx)*fy;
}
static unsigned char byte(float x) { return (unsigned char)(x<0?0:(x>255?255:x)); }
int main(int argc,char **argv) {
    if(argc!=2) return 2;
    FILE *f=fopen(argv[1],"wb"); if(!f) return 3;
    fputs("// Generated by tools/bake_detail.c; height / roughness / oxidation / wear.\n"
          "#ifndef DETAIL_ATLAS_H\n#define DETAIL_ATLAS_H\n#define DETAIL_ATLAS_SIDE 256\n"
          "static const unsigned char detail_atlas_bytes[262144] = {\n",f);
    uint32_t checksum=2166136261u;
    for(int y=0;y<SIDE;y++) for(int x=0;x<SIDE;x++) {
        uint32_t h=hash((uint32_t)x*1597334677u^(uint32_t)y*3812015801u^94u);
        float broad=noise(x/32.0f,y/32.0f,8,1051u);
        float corrosion=noise(x/8.0f,y/8.0f,32,293u);
        float rolled=noise(x/64.0f,y/2.0f,128,673u);
        float scratch=0;
        for(int layer=0;layer<3;layer++) {
            int cy=y/(8+layer*8),cx=x/32;
            uint32_t line=hash((uint32_t)cy*977u^(uint32_t)cx*577u^(uint32_t)layer);
            int ly=y%(8+layer*8),target=(int)(line%(uint32_t)(8+layer*8));
            if(ly==target && (x%32)<(int)((line>>8)&31u) && (line&3u)==0) scratch=1;
        }
        float pit=corrosion>0.63f && (h&31u)<5u?1.0f:0.0f;
        // Independent sub-pixel material channels carry useful surface data.
        unsigned char p[4]={byte(91+broad*43+rolled*20+(h&15u)-scratch*42-pit*35),
            byte(83+corrosion*60+((h>>9)&63u)-scratch*27),
            byte(30+powf(broad,2.0f)*98+corrosion*50+pit*40),
            byte(24+((h>>19)&31u)+scratch*175+pit*32)};
        for(int c=0;c<4;c++) { checksum=(checksum^p[c])*16777619u; fprintf(f,"%u,",p[c]); }
        if((x&7)==7) fputc('\n',f);
    }
    fputs("};\n#endif\n",f);
    if(fclose(f)!=0) return 4;
    printf("DETAIL BAKE: %dx%d RGBA, %d meaningful bytes, FNV1a=%08x\n",SIDE,SIDE,SIDE*SIDE*4,checksum);
    return 0;
}
